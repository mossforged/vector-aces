// Builds src/data/gen/content.js from the community xwing-data set + our catalog.
//
//   git clone --depth 1 https://github.com/guidokessels/xwing-data /tmp/xwing-data
//   node tools/xwing-import/build.mjs /tmp/xwing-data
//
// The dataset files are read as JSON (never executed). Only mechanics are copied:
// stats, actions, dials, costs, slots, weapon values, restrictions. Names, text and
// art come from catalog.js.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as CAT from './catalog.js';

const dataDir = path.join(process.argv[2] || '', 'data');
if (!fs.existsSync(path.join(dataDir, 'ships.js'))) {
  console.error('usage: node tools/xwing-import/build.mjs <path to xwing-data checkout>');
  process.exit(1);
}
const read = f => JSON.parse(fs.readFileSync(path.join(dataDir, f), 'utf8'));
const dsShips = read('ships.js'), dsPilots = read('pilots.js'), dsUpgrades = read('upgrades.js');
const byId = list => Object.fromEntries(list.map(x => [x.id, x]));
const S = byId(dsShips), P = byId(dsPilots), U = byId(dsUpgrades);

// "1BG" → "1BL:g"
const BEARING = { T: 'TL', B: 'BL', F: 'S', N: 'BR', Y: 'TR', K: 'K' };
function dial(codes, name) {
  return codes.map(c => {
    const speed = parseInt(c, 10), b = c.slice(String(speed).length, -1), col = c.slice(-1).toLowerCase();
    if (!BEARING[b]) throw new Error(`${name}: unsupported maneuver ${c}`);
    return `${speed}${BEARING[b]}:${col}`;
  });
}
const range = r => { const [a, b] = String(r).split('-').map(Number); return [a, b ?? a]; };

const shipIdByName = {};
const ships = {};
for (const [dsId, c] of Object.entries(CAT.SHIPS)) {
  const s = S[dsId];
  shipIdByName[s.name] = c.id;
  const faction = c.faction || CAT.FACTION_MAP[s.faction.find(f => CAT.FACTION_MAP[f])];
  ships[c.id] = {
    id: c.id, name: c.name, faction, size: s.size,
    attack: s.attack, agility: s.agility, hull: s.hull, shields: s.shields,
    actions: s.actions.map(a => CAT.ACTION_MAP[a]).filter(Boolean),
    arcs: ['front'],
    art: c.art,
    dial: dial(s.dial, s.name),
  };
}

// Every ship has an implicit Modification slot; ships with a title card get a Title slot.
const titleShips = new Set(Object.keys(CAT.UPGRADES).flatMap(id => (U[id].slot === 'Title' ? U[id].ship || [] : [])));

const pilots = {};
for (const [dsId, c] of Object.entries(CAT.PILOTS)) {
  const p = P[dsId];
  const ship = shipIdByName[p.ship];
  if (!ship) throw new Error(`pilot ${dsId}: ship ${p.ship} not imported`);
  pilots[c.id] = {
    id: c.id, ship, name: c.name, skill: p.skill, cost: p.points,
    ...(p.unique ? { unique: true } : {}),
    slots: [...p.slots.map(x => CAT.SLOT_MAP[x]).filter(Boolean), 'mod', ...(titleShips.has(p.ship) ? ['title'] : [])],
    ...(c.text ? { ability: c.id, text: c.text } : { text: '' }),
  };
}

const upgrades = {};
for (const [dsId, c] of Object.entries(CAT.UPGRADES)) {
  const u = U[dsId];
  const out = { id: c.id, slot: CAT.SLOT_MAP[u.slot], name: c.name, cost: u.points };
  if (u.unique) out.unique = true;
  if (u.faction) out.faction = CAT.FACTION_MAP[u.faction];
  if (u.ship) out.ships = u.ship.map(n => shipIdByName[n]).filter(Boolean);
  if (u.size) out.sizes = u.size;
  if (c.weapon) {
    const [minRange, maxRange] = range(u.range);
    out.weapon = { attack: u.attack, minRange, maxRange, cost: null, spend: false, discard: false, turret: false, ...c.weapon };
  }
  out.text = c.text;
  upgrades[c.id] = out;
}

const line = obj => JSON.stringify(obj);
const block = (name, obj) => `export const ${name} = {\n${Object.entries(obj).map(([k, v]) => `  ${JSON.stringify(k)}: ${line(v)},`).join('\n')}\n};\n`;
const out = `// GENERATED by tools/xwing-import/build.mjs — do not edit by hand.
// Edit tools/xwing-import/catalog.js (names/text) and re-run the build.
// Mechanics from the community xwing-data set (github.com/guidokessels/xwing-data).

${block('GEN_SHIPS', ships)}
${block('GEN_PILOTS', pilots)}
${block('GEN_UPGRADES', upgrades)}`;

const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.join(here, '../../src/data/gen/content.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`wrote ${dest}: ${Object.keys(ships).length} ships, ${Object.keys(pilots).length} pilots, ${Object.keys(upgrades).length} upgrades`);
